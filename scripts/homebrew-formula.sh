#!/usr/bin/env sh
# Print the Homebrew formula for a published release: the prebuilt vci binary
# for each platform, plus the collectors (pytest, Vitest, Ruby) from the
# tagged source, installed under share/vci where vci finds them.
#
#   scripts/homebrew-formula.sh v0.3.0 > Formula/vci.rb
#
# The release workflow runs this after the binaries are uploaded and pushes the
# result to PandelisZ/homebrew-tap.
set -eu
tag="${1:?usage: homebrew-formula.sh <tag>}"
repo="${VCI_REPO_SLUG:-PandelisZ/cryptographically-verifiable-ci-runner}"
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

sha256() { if command -v sha256sum >/dev/null 2>&1; then sha256sum "$1"; else shasum -a 256 "$1"; fi | cut -d' ' -f1; }

gh release download "$tag" --repo "$repo" --pattern 'SHA256SUMS-*' --dir "$tmp"
asset_sha() { cut -d' ' -f1 "$tmp/SHA256SUMS-$1"; }

source_url="https://github.com/$repo/archive/refs/tags/$tag.tar.gz"
curl -fsSL "$source_url" -o "$tmp/source.tar.gz"
source_sha="$(sha256 "$tmp/source.tar.gz")"
# The license of the tagged source, not of this checkout.
manifest="$(tar -tzf "$tmp/source.tar.gz" | grep -m1 '^[^/]*/Cargo\.toml$')"
license="$(tar -xzOf "$tmp/source.tar.gz" "$manifest" | sed -n 's/^license = "\(.*\)"/\1/p')"
[ -n "$license" ] || { echo "no license in $manifest of $tag" >&2; exit 1; }

base="https://github.com/$repo/releases/download/$tag"
cat <<RUBY
# Generated by scripts/homebrew-formula.sh in $repo. Do not edit by hand.
class Vci < Formula
  desc "Skip tests a trusted signer already ran against identical inputs"
  homepage "https://pandelisz.github.io/cryptographically-verifiable-ci-runner/"
  license "$license"
  # Homebrew cannot read the version from URLs inside on_macos/on_linux blocks.
  version "${tag#v}"

  on_macos do
    on_arm do
      url "$base/vci-aarch64-apple-darwin.tar.gz"
      sha256 "$(asset_sha aarch64-apple-darwin)"
    end
    on_intel do
      url "$base/vci-x86_64-apple-darwin.tar.gz"
      sha256 "$(asset_sha x86_64-apple-darwin)"
    end
  end

  on_linux do
    on_arm do
      url "$base/vci-aarch64-unknown-linux-musl.tar.gz"
      sha256 "$(asset_sha aarch64-unknown-linux-musl)"
    end
    on_intel do
      url "$base/vci-x86_64-unknown-linux-musl.tar.gz"
      sha256 "$(asset_sha x86_64-unknown-linux-musl)"
    end
  end

  resource "collectors" do
    url "$source_url"
    sha256 "$source_sha"
  end

  def install
    # vci finds share/vci/pytest-plugin and share/vci/ruby-collector next to
    # its executable; the Vitest package is passed through VCI_JS_PLUGIN.
    (libexec/"bin").install "vci"
    resource("collectors").stage do
      pkgshare.install "py/pytest-plugin"   => "pytest-plugin",
                       "ruby/vci-collector" => "ruby-collector",
                       "js/vitest-plugin"   => "vitest-plugin"
    end
    (bin/"vci").write_env_script libexec/"bin/vci",
                                 VCI_JS_PLUGIN: "\${VCI_JS_PLUGIN:-#{opt_pkgshare}/vitest-plugin}"
  end

  test do
    assert_match "vci", shell_output("#{bin}/vci --version")
    assert_path_exists pkgshare/"pytest-plugin/vci_pytest/__init__.py"
    assert_path_exists pkgshare/"ruby-collector/vci_collector.rb"
    assert_path_exists pkgshare/"vitest-plugin/package.json"
  end
end
RUBY
